/** 给 AI 的使用指引（会话首步注入与 ts_guide 共用同一份文本）。 */
export const TS_GUIDE = `TypeSafe System One 是「可编程的常识」：把自然语言与状态变成**类型化判定**
（Choice / Noul / Score），由代码组合使用。它不生成文字、不给理由，只给可以 if 的结论与概率。

## 什么时候该用它（而不是 if/else，也不是让大模型自由发挥）

- 需要一个**语义判断**才能分支：分诊、路由、分类、抽取、排序、校验、意图识别；
- 原本靠一堆关键词/正则堆出启发式，而且**文案一改就失效**；
- 原本用大模型「prompt 出文本再解析」，其实要的只是一个结构化结论。

## 三种原语怎么选（按「答案是什么意思」选，不按手感选）

| 需求 | 原语 | 关键区别 |
| --- | --- | --- |
| 从**定义好的集合**里选一个 | choice | 返回选中项 + 各选项概率（probabilities 用于比较竞争选项） |
| 判断**某个条件是否成立** | noul | 只给「是」的概率；0.5 附近表示是非概率相近，不是程度中等；多个标签可能同时成立时，每个标签各用一个 noul |
| 沿**某个维度**给程度/等级 | score | 概率加权的位置；同口径的多个 score 可用于排序 |

## 怎么设计判断（决定成败的地方）

1. **一道问题只问一件事**。独立维度拆开问，但不要拆散它们之间的关系。
2. **问题 id 只给代码用，不会发给模型**。判断的全部含义必须写进 instructions。
3. **判断写进 instructions，答案定义写进 criteria**。criteria 的每个值都要模型能独立读懂。
4. **给足状态**：原文、身份、关系、政策、当前事实。多部分上下文用**命名 JSON 字段**
   （如 ticket.messages[0].text），并在 instructions 里用反引号引用路径。
5. **模型选不出没给的候选**：做抽取或指定值时，候选必须由代码先枚举进 criteria。
6. **独立的问题一起问**。它们并行执行、互相看不见，所以「如果有用」的推测性问题也可以一起发。
7. **只有需要前一个答案才能构造下一个状态时，才发第二次请求。**

## 怎么消费结果（code owns the workflow）

- **阈值是代码的事，且在真实数据上调**。confidence 只表示分布集中度，**不表示流程正确**，
  也不代表可以放行；noul 接近 0.5 要当作「拿不准」，交给代码兜底或升级人工。
- **保留原始判定，别把策略写死进问题里**：先拿可复用的判定，权重与阈值变化时不必重跑推理。
- **概率可供组合**：加权求和适合可补偿的偏好；「任何一条严重违规都不能接受」要用独立条件判断。
- **类型化只保证接口，不保证真相**。要用真实样本验证判定质量，别把 cookbook 的阈值当普适真理。
- **失败要分辨来源**：缺证据、模型判错、代码写错、服务不可用，是四件不同的事。

## 安全

密钥只留在服务端/进程环境（本插件从环境变量或 600 权限的密钥文件读取），**绝不写进前端或返回给用户**。`
